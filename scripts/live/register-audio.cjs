// No synthesis or network call. Register only human-approved, rights-cleared recordings.
const fs = require("node:fs"),
  path = require("node:path"),
  crypto = require("node:crypto");
const root = path.resolve(__dirname, "../.."),
  stories = JSON.parse(
    fs.readFileSync(path.join(root, "src/data/live/stories.json"), "utf8"),
  );
const manifest = JSON.parse(
  fs.readFileSync(path.join(root, "src/data/live/audio-manifest.json"), "utf8"),
);
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");
const records = [];
for (const s of stories) {
  if (sha(s.script) !== s.contentHash)
    throw Error(`Script hash mismatch: ${s.id}`);
  if (s.status === "live_editorial_approved") {
    const a = s.approval;
    if (
      s.origin !== "vestige_editorial" ||
      !a ||
      a.humanReview !== true ||
      !a.approvedBy?.trim() ||
      !Number.isFinite(Date.parse(a.approvedAt)) ||
      a.version !== s.version ||
      a.contentHash !== s.contentHash ||
      a.approvedText !== s.script
    )
      throw Error(`Human version approval missing: ${s.id}`);
    if (!s.audioId || !manifest.some((m) => m.id === s.audioId))
      throw Error(`Approved recording missing: ${s.id}`);
  }
}
for (const a of manifest) {
  const s = stories.find((s) => s.id === a.storyId);
  if (
    !s ||
    s.status !== "live_editorial_approved" ||
    s.audioId !== a.id ||
    s.contentHash !== a.contentHash ||
    s.version !== a.scriptVersion ||
    !a.rightsHolder?.trim() ||
    !a.license?.trim()
  )
    throw Error(`Audio rights or version mismatch: ${a.id}`);
  if (!/^assets\/live\/[a-z0-9/_-]+\.(mp3|m4a|wav)$/.test(a.file))
    throw Error("Audio must be a versioned local file under assets/live");
  const file = path.join(root, a.file);
  if (sha(fs.readFileSync(file)) !== a.sha256)
    throw Error(`Audio hash mismatch: ${a.id}`);
  const { file: _, ...metadata } = a;
  records.push(
    `${JSON.stringify(a.id)}: { ...${JSON.stringify(metadata)}, module:require(${JSON.stringify("../../../" + a.file)}) }`,
  );
}
const output =
  '// Generated by scripts/live/register-audio.cjs. No approved recordings yet if empty.\nimport type {LiveAsset} from "../../lib/live/types";\nexport const liveAssets:Record<string,LiveAsset>={' +
  records.join(",\n") +
  "};\n";
if (!process.argv.includes("--check"))
  fs.writeFileSync(path.join(root, "src/data/live/audioAssets.ts"), output);
console.log(
  `Live catalogue validated: ${stories.length} scripts, ${records.length} approved recordings.`,
);
