const statuses = {
  editorial_verified: "#E6AD4F",
  community_unreviewed: "#26CAD8",
  community_pending: "#F29D38",
  community_verified: "#7BCB56",
  imported_unreviewed: "#8596A9",
  editorial_unreviewed: "#8596A9",
};
const question = '<path d="M40 39c0-3 5-3 5 0 0 2-3 2-3 4m0 2h.01"/>';
const people =
  '<circle cx="40" cy="38" r="1.8"/><circle cx="45" cy="39" r="1.4"/><path d="M37 44v-1c0-3 6-3 6 0v1m1-3c2 0 3 1 3 3"/>';
function seal(status) {
  if (status === "editorial_verified")
    return '<path d="M42 34l6 2v5c0 4-6 7-6 7s-6-3-6-7v-5z" fill="#269DE4" stroke="#E6AD4F"/><path d="m39 40 2 2 4-5" stroke="white"/>';
  let symbol =
    status === "editorial_unreviewed"
      ? '<path d="M36 37q3-2 6 0 3-2 6 0v8q-3-2-6 0-3-2-6 0zM42 37v8"/>'
      : status === "community_pending"
        ? '<circle cx="42" cy="41" r="4"/><path d="M42 38v3l2 1"/>'
        : status.startsWith("community")
          ? people
          : '<path d="M38 35h6l3 3v9h-9z"/>' + question;
  if (status === "community_verified")
    symbol += '<path d="m42 44 2 2 4-4" stroke="#7BCB56" stroke-width="2"/>';
  return `<circle cx="42" cy="41" r="9" fill="#081626" stroke="${statuses[status]}"/>${symbol}`;
}
function artwork(category, status, illustration) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="156" height="168" viewBox="0 0 52 56"><defs><linearGradient id="bg" x2=".8" y2="1"><stop stop-color="#24365D"/><stop offset="1" stop-color="#081626"/></linearGradient></defs><ellipse cx="26" cy="46" rx="18" ry="5" fill="#4FA8EC" opacity=".12"/><ellipse cx="26" cy="51" rx="15" ry="2.4" fill="#020814" opacity=".3"/><path d="m22 43 4 7 4-7" fill="${statuses[status]}"/><rect x="7" y="9" width="38" height="36" rx="13" fill="url(#bg)" stroke="${statuses[status]}" stroke-width="2"/><path d="M15 13h15" stroke="#E6CA8B" opacity=".6" stroke-linecap="round"/><g fill="none" stroke="#F1F5FB" stroke-width="1.65" stroke-linecap="round" stroke-linejoin="round">${illustration ?? categories[category]}</g><g fill="none" stroke="#F1F5FB" stroke-width="1.2" stroke-linecap="round" stroke-linejoin="round">${seal(status)}</g></svg>`;
}
module.exports = { artwork, statuses };
if (require.main === module) {
  let registry =
    '// Generated by scripts/poi/build-markers.cjs\nimport type { PoiCategory, PoiStatus } from "../../lib/poi";\nimport type { ImageSourcePropType } from "react-native";\nexport const poiAssets: Record<PoiCategory, Record<PoiStatus, ImageSourcePropType>> = {\n';
  for (const category of Object.keys(categories)) {
    registry += `${category}: {\n`;
    for (const status of Object.keys(statuses)) {
      const svg = artwork(category, status);
      const base = `assets/poi/${category}-${status}`;
      fs.writeFileSync(path.join(root, base + ".svg"), svg);
      fs.writeFileSync(
        path.join(root, base + ".png"),
        new Resvg(svg).render().asPng(),
      );
      registry += `${status}: require("../../../${base}.png"),\n`;
    }
    registry += "},\n";
  }
  registry += "};\n";
  fs.writeFileSync(path.join(root, "src/components/poi/assets.ts"), registry);
}
