// Build compact map pins. PNGs keep the same native image loading path on iOS
// and Android, with separate densities for crisp edges.
const fs = require("node:fs");
const path = require("node:path");
const { Resvg } = require("@resvg/resvg-js");
const root = path.resolve(__dirname, "../..");
const glyphs = {
  temple: '<path d="M3 8l9-5 9 5v2H3zM5 20h14M7 10v8m5-8v8m5-8v8M3 22h18"/>',
  museum:
    '<rect x="3" y="4" width="18" height="16" rx="2"/><circle cx="9" cy="9" r="1"/><path d="m4 17 5-4 3 3 4-5 4 5"/>',
  castle: '<path d="M4 21V6h4v4h2V6h4v4h2V6h4v15zM10 21v-5a2 2 0 0 1 4 0v5"/>',
  religious:
    '<path d="M12 2v5M9.5 4.5h5M5 21v-8l7-6 7 6v8zM10 21v-5a2 2 0 0 1 4 0v5"/>',
  industrial: '<path d="M3 21v-9l6-4v5l6-4v4h2V4h3l1 17zM7 17h1m3 0h1m3 0h1"/>',
  nature:
    '<path d="M12 21v-6m0 2c-4 0-7-3-7-6 0-2 1-4 3-5a4 4 0 0 1 8 0c2 1 3 3 3 5 0 3-3 6-7 6z"/>',
  other:
    '<path d="M6 21V11a6 6 0 0 1 12 0v10M3 21h18M10 21v-9a2 2 0 0 1 4 0v9"/>',
};
const modes = [
  "idle",
  "nearby",
  "discovered",
  "selected",
  "discovered-selected",
];
const out = path.join(root, "assets/poi/map-pins");
fs.mkdirSync(out, { recursive: true });
const registry = [];

for (const [category, glyph] of Object.entries(glyphs)) {
  const images = [];
  for (const mode of modes) {
    const selected = mode.includes("selected");
    const discovered = mode.includes("discovered");
    const nearby = mode === "nearby";
    const accent = selected ? "#F7D890" : nearby ? "#F1AC79" : "#DECBA4";
    const fill = selected ? "#F7D890" : "#162639";
    const ink = selected ? "#182638" : "#FFF1D6";
    const badge = discovered
      ? '<circle cx="47" cy="31" r="7" fill="#254E42" stroke="#F4EDD9" stroke-width="1.4"/><path d="m44 31 2 2 4-4" fill="none" stroke="#F4EDD9" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round"/>'
      : "";
    const body = `<path d="M32 24a17 17 0 0 1 17 17c0 9-7 13-17 23-10-10-17-14-17-23a17 17 0 0 1 17-17z" fill="${fill}" stroke="${accent}" stroke-width="${selected || nearby ? 2 : 1.3}" stroke-linejoin="round"/><g transform="translate(22 30) scale(.8333)" fill="none" stroke="${ink}" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${glyph}</g>${badge}`;
    const name = `${category}-${mode}`;
    for (const scale of [1, 2, 3]) {
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${64 * scale}" height="${72 * scale}" viewBox="0 0 64 72">${body}</svg>`;
      const suffix = scale === 1 ? "" : `@${scale}x`;
      fs.writeFileSync(
        path.join(out, name + suffix + ".png"),
        new Resvg(svg).render().asPng(),
      );
    }
    images.push(
      `    "${mode}": require("../../../assets/poi/map-pins/${name}.png"),`,
    );
  }
  registry.push(`  ${category}: {\n${images.join("\n")}\n  },`);
}

fs.writeFileSync(
  path.join(root, "src/components/poi/nativeMapAssets.ts"),
  `// Generated by scripts/poi/build-native-map.cjs.
import type { ImageRequireSource } from "react-native";
import type { PoiCategory } from "../../lib/poi";
import type { MonumentState } from "../../lib/markerState";
import { nativePoiMode, type NativePoiMode } from "../../lib/poiMapRendering";

const nativePoiAssets: Record<PoiCategory, Record<NativePoiMode, ImageRequireSource>> = {
${registry.join("\n")}
};

export function nativePoiImage(category: PoiCategory, state: MonumentState, selected: boolean) {
  return nativePoiAssets[category][nativePoiMode(state, selected)];
}
`,
);
