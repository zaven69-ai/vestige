// Rasterize the SAME UI layers as PoiGlyph for Marker.image.
// Original category illustrations remain untouched. Native markers never need
// to snapshot three asynchronous React Native Image children.
const fs = require("node:fs"),
  path = require("node:path");
const { Resvg } = require("@resvg/resvg-js");
const root = path.resolve(__dirname, "../..");
const categories = [
  "temple",
  "museum",
  "castle",
  "religious",
  "industrial",
  "nature",
  "other",
];
const statuses = [
  "editorial_verified",
  "community_unreviewed",
  "community_pending",
  "community_verified",
  "imported_unreviewed",
  "editorial_unreviewed",
];
const modes = [
  "idle",
  "nearby",
  "discovered",
  "selected",
  "discovered-selected",
];
const data = (file) =>
  "data:image/png;base64," +
  fs
    .readFileSync(path.join(root, "assets/poi", file + ".png"))
    .toString("base64");
const out = path.join(root, "assets/poi/map-native");
fs.mkdirSync(out, { recursive: true });
let registry =
  '// Generated by scripts/poi/build-native-map.cjs. Native bitmap markers.\nimport type { ImageRequireSource } from "react-native";\nimport type { PoiCategory, PoiStatus } from "../../lib/poi";\nimport type { MonumentState } from "../../lib/markerState";\nimport { nativePoiMode, type NativePoiMode } from "../../lib/poiMapRendering";\nexport const nativePoiAssets:Record<PoiCategory,Record<PoiStatus,Record<NativePoiMode,ImageRequireSource>>> = {\n';
const reviews = Object.fromEntries(
  statuses.map((status) => [status, data("review/" + status)]),
);
const discovery = {
  none: data("discovery/undiscovered"),
  discovered: data("discovery/discovered"),
};
for (const category of categories) {
  const scene = data("illustrated/" + category);
  registry += `${category}:{\n`;
  for (const status of statuses) {
    registry += `${status}:{\n`;
    for (const mode of modes) {
      const selected = mode.includes("selected"),
        found = mode.includes("discovered");
      const halo =
        selected || mode === "nearby"
          ? `<ellipse cx="32" cy="31" rx="30" ry="29" fill="none" stroke="${selected ? "#F5D281" : "#F77B54"}" stroke-width="1.6"/>`
          : "";
      const body = `${halo}<image href="${scene}" x="2" y="2" width="60" height="66"/><image href="${reviews[status]}" x="44" y="43" width="20" height="20"/><image href="${found ? discovery.discovered : discovery.none}" x="0" y="1" width="18" height="18"/>`;
      const name = `${category}-${status}-${mode}`;
      for (const scale of [1, 2, 3]) {
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${64 * scale}" height="${72 * scale}" viewBox="0 0 64 72">${body}</svg>`;
        const suffix = scale === 1 ? "" : `@${scale}x`;
        fs.writeFileSync(
          path.join(out, name + suffix + ".png"),
          new Resvg(svg).render().asPng(),
        );
      }
      registry += `"${mode}":require("../../../assets/poi/map-native/${name}.png"),\n`;
      if (global.gc) global.gc();
    }
    registry += "},\n";
  }
  registry += "},\n";
  console.log("Built native family", category);
}
registry +=
  "};\nexport function nativePoiImage(category:PoiCategory,status:PoiStatus,state:MonumentState,selected:boolean){return nativePoiAssets[category][status][nativePoiMode(state,selected)];}\n";
fs.writeFileSync(
  path.join(root, "src/components/poi/nativeMapAssets.ts"),
  registry,
);
